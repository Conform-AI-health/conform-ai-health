export function normalizeNavigationLabel(value: string): string {
  let withoutPrefix = value.replace(/\[([^\]]+)\]\([^)]+\)/g, '$1').trim();
  const prefixPattern = /^\s*(?:(?:[•·▪◦‣⁃*-]+)|(?:\d+\s*[.)-])|(?:[a-z]\s*[.)]))\s*/i;
  let previous: string;
  do {
    previous = withoutPrefix;
    withoutPrefix = withoutPrefix.replace(prefixPattern, '');
  } while (withoutPrefix !== previous);

  return withoutPrefix
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/\s+/g, ' ')
    .trim();
}

export function isNavigationLabel(value: string): boolean {
  const normalized = normalizeNavigationLabel(value);
  return NAV_LABELS.has(normalized) || NAV_PATTERNS.some((pattern) => pattern.test(normalized));
}
